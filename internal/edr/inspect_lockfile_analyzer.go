package edr

// Lockfile analyzer (kind "lockfile"): software composition analysis of
// SUBMITTED dependency files. It parses text only, never executes anything,
// never reads other files, makes no network call and sends no component name
// anywhere. Advisory matching uses the data Kavach has already loaded locally
// (embedded sample, KAVACH_CVE_FILE, cached KEV/OSV feeds) through the same
// vmMatch/osvFindings/markKEV code the host inventory uses.

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"regexp"
	"sort"
	"strings"
)

func init() {
	RegisterAnalyzer("lockfile", []string{InspectKindLockfile}, analyzeLockfile)
}

// Weights (documented in docs/lockfile-inspection.md).
const (
	lfSCACap        = 60
	lfWUnpinned     = 4
	lfWRange        = 3
	lfWNoIntegrity  = 2
	lfWGit          = 6
	lfWHTTP         = 6
	lfWTyposquat    = 3
	lfWKnownMal     = 50
	lfMaxSBOMComps  = 10000
	lfMaxHygExample = 8
)

var lfNPMNames = map[string]bool{"package-lock.json": true, "npm-shrinkwrap.json": true}

// lfDetect picks the format from the client-supplied name first, then from
// content. Returns "" when it cannot tell.
func lfDetect(name string, data []byte) string {
	base := strings.ToLower(name)
	if i := strings.LastIndexAny(base, `/\`); i >= 0 {
		base = base[i+1:]
	}
	switch {
	case lfNPMNames[base]:
		return "npm"
	case base == "yarn.lock":
		return "yarn"
	case base == "pnpm-lock.yaml":
		return "pnpm"
	case base == "pipfile.lock":
		return "pipfile"
	case base == "poetry.lock":
		return "poetry"
	case base == "cargo.lock":
		return "cargo"
	case base == "gemfile.lock":
		return "gem"
	case base == "composer.lock":
		return "composer"
	case base == "go.mod":
		return "gomod"
	case base == "go.sum":
		return "gosum"
	case base == "pom.xml":
		return "pom"
	case base == "packages.lock.json":
		return "nuget"
	case base == "gradle.lockfile" || strings.HasSuffix(base, ".lockfile"):
		return "gradle"
	case strings.HasPrefix(base, "requirements") && strings.HasSuffix(base, ".txt"):
		return "requirements"
	}
	head := data
	if len(head) > 64<<10 {
		head = head[:64<<10]
	}
	t := strings.TrimSpace(string(head))
	if t == "" {
		return ""
	}
	if t[0] == '{' {
		var probe map[string]json.RawMessage
		if json.Unmarshal(data, &probe) == nil {
			_, lv := probe["lockfileVersion"]
			_, meta := probe["_meta"]
			_, ch := probe["content-hash"]
			_, pk := probe["packages"]
			_, deps := probe["dependencies"]
			_, ver := probe["version"]
			switch {
			case lv:
				return "npm"
			case meta:
				return "pipfile"
			case ch || (pk && probe["packages-dev"] != nil) || probe["packages-dev"] != nil:
				return "composer"
			case deps && ver:
				return "nuget"
			}
		}
		return ""
	}
	switch {
	case strings.HasPrefix(t, "<?xml") || strings.HasPrefix(t, "<project"):
		return "pom"
	case strings.Contains(t, "# yarn lockfile v1") || strings.Contains(t, "\n__metadata:") || strings.HasPrefix(t, "__metadata:"):
		return "yarn"
	case regexp.MustCompile(`(?m)^lockfileVersion:`).MatchString(t):
		return "pnpm"
	case strings.Contains(t, "[[package]]"):
		if strings.Contains(t, "[metadata]") && (strings.Contains(t, "content-hash") || strings.Contains(t, "python-versions")) {
			return "poetry"
		}
		if strings.Contains(t, "checksum") || strings.Contains(t, "\nsource = \"registry+") || strings.HasPrefix(t, "# This file is automatically @generated by Cargo") {
			return "cargo"
		}
		return "poetry"
	case regexp.MustCompile(`(?m)^module\s+\S+`).MatchString(t) || regexp.MustCompile(`(?m)^require[\s(]`).MatchString(t):
		return "gomod"
	case regexp.MustCompile(`(?m)^\S+ v\S+ h1:\S+$`).MatchString(t):
		return "gosum"
	case regexp.MustCompile(`(?m)^(GEM|GIT|PATH)\s*$`).MatchString(t):
		return "gem"
	case regexp.MustCompile(`(?m)^(ii|hi|iU)\s+\S+\s+\S+\s+\S+`).MatchString(t):
		return "dpkg"
	case regexp.MustCompile(`(?m)^[\w.+-]+:[\w.+-]+:[\w.+-]+(=.*)?$`).MatchString(t) && strings.Contains(t, "="):
		return "gradle"
	}
	// rpm -qa vs apk info -v: judge by the first non-empty lines
	rpm, apk, n := 0, 0, 0
	for _, ln := range strings.Split(t, "\n") {
		ln = strings.TrimSpace(ln)
		if ln == "" {
			continue
		}
		if n++; n > 50 {
			break
		}
		switch {
		case lfRPMRe.MatchString(ln):
			rpm++
		case lfApkRe.MatchString(ln):
			apk++
		}
	}
	if n > 0 && (rpm > 0 || apk > 0) && rpm+apk*1 >= n/2 {
		if rpm >= apk {
			return "rpm"
		}
		return "apk"
	}
	if regexp.MustCompile(`(?m)^[A-Za-z0-9][A-Za-z0-9._-]*\s*(\[.*\])?\s*(==|>=|<=|~=|!=|<|>|===)`).MatchString(t) {
		return "requirements"
	}
	return ""
}

func lfParse(format string, data []byte) (*lfResult, error) {
	switch format {
	case "npm":
		return lfParseNPM(data)
	case "yarn":
		return lfParseYarn(data)
	case "pnpm":
		return lfParsePnpm(data)
	case "requirements":
		return lfParseRequirements(data)
	case "pipfile":
		return lfParsePipfileLock(data)
	case "poetry":
		return lfParsePoetry(data)
	case "cargo":
		return lfParseCargo(data)
	case "gomod":
		return lfParseGoMod(data)
	case "gosum":
		return lfParseGoSum(data)
	case "gem":
		return lfParseGemfileLock(data)
	case "composer":
		return lfParseComposer(data)
	case "pom":
		return lfParsePom(data)
	case "gradle":
		return lfParseGradle(data)
	case "nuget":
		return lfParseNuGet(data)
	case "dpkg":
		return lfParseDpkg(data)
	case "rpm":
		return lfParseRPMList(data)
	case "apk":
		return lfParseApkList(data)
	}
	return nil, fmt.Errorf("unknown lockfile format %q", format)
}

func lfInputBytes(in InspectInput) []byte {
	if len(in.Data) > 0 {
		return in.Data
	}
	return []byte(in.Text)
}

func lfLabel(c lfComp) string {
	if c.Version == "" {
		return c.Name
	}
	return c.Name + "@" + c.Version
}

func analyzeLockfile(ctx context.Context, in InspectInput, b *InspectBuilder) error {
	data := lfInputBytes(in)
	if len(data) == 0 {
		return fmt.Errorf("empty input")
	}
	data = bytes.TrimPrefix(data, []byte("\xef\xbb\xbf"))
	format := lfDetect(in.Name, data)
	if format == "" {
		b.Finding(InspectFinding{ID: "sca-format-unknown", Title: "Dependency file format not recognised", Severity: "info",
			Evidence: "supported: package-lock.json, yarn.lock v1, pnpm-lock.yaml, requirements.txt, Pipfile.lock, poetry.lock, go.mod, go.sum, Cargo.lock, Gemfile.lock, composer.lock, pom.xml, gradle lockfile, packages.lock.json, dpkg -l, rpm -qa, apk info -v"})
		b.Meta("format", "unknown")
		return nil
	}
	res, err := lfParse(format, data)
	if err != nil {
		b.Finding(InspectFinding{ID: "sca-parse-error", Title: "Dependency file could not be parsed", Severity: "info", Evidence: err.Error()})
		b.Format(format)
		b.Meta("format", format)
		return nil
	}
	if ctx.Err() != nil {
		return ctx.Err()
	}
	b.Format(res.Format)
	if len(res.Comps) >= lfMaxComps {
		b.LimitHit("components")
	}
	comps := lfDedupe(res.Comps)

	eco := map[string]int{}
	direct := 0
	for _, c := range comps {
		eco[c.Eco]++
		if c.Direct == "direct" {
			direct++
		}
	}
	b.Meta("format", res.Format)
	b.Meta("summary", map[string]any{"components": len(comps), "direct": direct, "ecosystems": eco, "notes": res.Notes,
		"version_schemes": lfSchemesUsed(comps)})
	if len(res.Notes) > 0 {
		b.Finding(InspectFinding{ID: "sca-limits", Title: "Parsing limits for this file", Severity: "info", Evidence: strings.Join(res.Notes, "; ")})
	}

	vulns := lfMatch(ctx, comps)
	lfEmitVulns(b, vulns)
	lfEmitHygiene(b, res, comps)
	lfEmitMalicious(b, comps)

	sbom, trunc := lfCycloneDX(in, comps, vulns)
	if trunc {
		b.LimitHit("sbom-components")
	}
	b.Meta("sbom", sbom)
	return nil
}

func lfDedupe(in []lfComp) []lfComp {
	seen := map[string]int{}
	out := make([]lfComp, 0, len(in))
	for _, c := range in {
		k := c.Eco + "|" + strings.ToLower(c.Name) + "|" + c.Version
		if c.Version == "" {
			k += "|" + c.Spec + "|" + c.Resolved
		}
		if i, ok := seen[k]; ok {
			if out[i].Direct != "direct" && c.Direct == "direct" {
				out[i].Direct = "direct"
			}
			continue
		}
		seen[k] = len(out)
		out = append(out, c)
	}
	return out
}

func lfSchemesUsed(comps []lfComp) map[string]string {
	m := map[string]string{}
	for _, c := range comps {
		if s := lfScheme(c.Eco); s != "" {
			m[c.Eco] = s
		} else {
			m[c.Eco] = "none (matching reported as unknown)"
		}
	}
	return m
}

// ---- advisory matching ----

// lfVuln is one matched advisory for one component.
type lfVuln struct {
	VMFinding
	Eco        string
	CmpUnknown bool
	SSVC       SSVCResult
}

// lfOSVEco maps our ecosystem to the string vfEcosystem understands.
func lfOSVEco(eco string) string {
	switch eco {
	case "deb":
		return "dpkg"
	case "composer":
		return "" // no OSV mapping in vfEcosystem
	}
	return eco
}

func lfMatch(ctx context.Context, comps []lfComp) []lfVuln {
	adv, _, _ := vmLoadAdvisoriesErr()
	names := map[string]bool{}
	for _, a := range adv {
		names[strings.ToLower(a.Package)] = true
	}
	var rows, advRows []map[string]any
	ecoOf := map[string]string{}
	for _, c := range comps {
		if c.Version == "" {
			continue
		}
		row := map[string]any{"component": c.Name, "version": c.Version, "ecosystem": lfOSVEco(c.Eco), "host": "lockfile"}
		rows = append(rows, row)
		ecoOf[strings.ToLower(c.Name)+"@"+c.Version] = c.Eco
		if names[strings.ToLower(c.Name)] {
			advRows = append(advRows, row)
		}
	}
	if ctx.Err() != nil {
		return nil
	}
	// Advisory-set matching: vmMatch is the inventory's own function; it is
	// quadratic, so it only sees rows whose name appears in the advisory set.
	fs := vmMatch(advRows, adv)
	for i := range fs {
		fs[i].Source = "advisory-set"
	}
	fs = append(fs, vmFeeds.osvFindings(rows)...) // cache read only
	vmFeeds.markKEV(fs)

	seen := map[string]bool{}
	var out []lfVuln
	for _, f := range fs {
		k := f.CVE + "|" + strings.ToLower(f.Package) + "|" + f.Version
		if seen[k] {
			continue
		}
		seen[k] = true
		eco := ecoOf[strings.ToLower(f.Package)+"@"+f.Version]
		v := lfVuln{VMFinding: f, Eco: eco}
		if f.Source != "osv" { // OSV entries were matched by exact version upstream
			cmp, ok := lfCompare(eco, f.Version, f.FixedIn)
			switch {
			case !ok:
				v.CmpUnknown = true
			case cmp >= 0:
				continue // not affected under the ecosystem's own ordering
			}
		}
		in, _, _ := vpBuildFactors(f, "", 0) // cache-only lookups, no network
		v.SSVC = ssvcEvaluate(in)
		out = append(out, v)
	}
	sort.SliceStable(out, func(i, j int) bool {
		if out[i].CVSS != out[j].CVSS {
			return out[i].CVSS > out[j].CVSS
		}
		return out[i].CVE < out[j].CVE
	})
	return out
}

func lfSeverity(cvss float64) string {
	switch {
	case cvss >= 9:
		return "critical"
	case cvss >= 7:
		return "high"
	case cvss >= 4:
		return "medium"
	case cvss > 0:
		return "low"
	}
	return "medium" // advisory carries no score: do not understate
}

func lfSevWeight(sev string) int {
	switch sev {
	case "critical":
		return 40
	case "high":
		return 25
	case "medium":
		return 12
	case "low":
		return 5
	}
	return 0
}

func lfEmitVulns(b *InspectBuilder, vulns []lfVuln) {
	budget := lfSCACap
	for _, v := range vulns {
		sev := lfSeverity(v.CVSS)
		w := lfSevWeight(sev)
		title := fmt.Sprintf("Vulnerable dependency %s %s (%s)", v.Package, v.Version, v.CVE)
		ev := fmt.Sprintf("%s@%s [%s]", v.Package, v.Version, v.Eco)
		if v.FixedIn != "" {
			ev += "; fixed in " + v.FixedIn
		} else {
			ev += "; fix version not stated by advisory"
		}
		if v.CVSS > 0 {
			ev += fmt.Sprintf("; CVSS %.1f", v.CVSS)
		} else {
			ev += "; advisory has no CVSS score (treated as medium)"
		}
		if v.KnownExploited {
			ev += "; CISA KEV (exploited in the wild)"
		}
		if v.CmpUnknown {
			sev, w = "low", 5
			title += " - version comparison unknown"
			ev += "; UNVERIFIED: version scheme for this ecosystem cannot order these versions, so affected/not-affected is unknown"
		}
		ev += fmt.Sprintf("; SSVC %s [range %s..%s, unknown inputs defaulted]; source %s; %s", v.SSVC.Outcome, v.SSVC.BestCase, v.SSVC.WorstCase, v.Source, v.Summary)
		if w > budget {
			w = budget
		}
		budget -= w
		b.Finding(InspectFinding{ID: "sca-" + strings.ToLower(v.CVE), Title: title, Severity: sev, Technique: "T1195.001", Evidence: ev, Weight: w})
	}
}

// ---- hygiene ----

func lfExamples(names []string) string {
	sort.Strings(names)
	n := len(names)
	if n > lfMaxHygExample {
		names = append(names[:lfMaxHygExample:lfMaxHygExample], fmt.Sprintf("... +%d more", n-lfMaxHygExample))
	}
	return strings.Join(names, ", ")
}

func lfEmitHygiene(b *InspectBuilder, res *lfResult, comps []lfComp) {
	var unpinned, rng, noInt, git, httpc []string
	for _, c := range comps {
		l := lfLabel(c)
		if c.Spec != "" && c.Version == "" {
			l = c.Name + " " + c.Spec
		}
		switch {
		case c.Unpinned:
			unpinned = append(unpinned, l)
		case c.Range:
			rng = append(rng, l)
		}
		if res.ExpectIntegrity && c.Integrity == "" && !c.Unpinned && !c.Range {
			noInt = append(noInt, l)
		}
		if c.Git {
			git = append(git, l)
		}
		if c.HTTP {
			httpc = append(httpc, l)
		}
	}
	emit := func(id, title, sev string, w int, names []string) {
		if len(names) == 0 {
			return
		}
		b.Finding(InspectFinding{ID: id, Title: fmt.Sprintf("%s (%d)", title, len(names)), Severity: sev, Technique: "T1195.001", Evidence: lfExamples(names), Weight: w})
	}
	emit("sca-unpinned", "Dependencies without a pinned version", "low", lfWUnpinned, unpinned)
	emit("sca-range", "Dependencies with a range or wildcard specifier", "low", lfWRange, rng)
	emit("sca-no-integrity", "Dependencies without an integrity hash", "low", lfWNoIntegrity, noInt)
	emit("sca-git-dependency", "Dependencies fetched from a git URL", "medium", lfWGit, git)
	emit("sca-insecure-registry", "Dependencies resolved over plain http", "medium", lfWHTTP, httpc)
	for _, h := range res.Extra {
		switch h.Kind {
		case "insecure-registry":
			b.Finding(InspectFinding{ID: "sca-insecure-registry", Title: "Registry or index configured over plain http", Severity: "medium", Technique: "T1195.001", Evidence: h.Evidence, Weight: lfWHTTP})
		case "git-dependency":
			b.Finding(InspectFinding{ID: "sca-git-dependency", Title: "Dependency fetched from a git URL", Severity: "medium", Technique: "T1195.001", Evidence: h.Evidence, Weight: lfWGit})
		}
	}
	// Typosquat-shaped names (edit distance 1 from a popular name; low).
	flagged := 0
	for _, c := range comps {
		if pop, ok := lfTyposquat(c.Eco, c.Name); ok {
			if flagged++; flagged > 20 {
				b.LimitHit("typosquat-findings")
				break
			}
			b.Finding(InspectFinding{ID: "sca-typosquat", Title: "Package name is one edit away from a popular package", Severity: "low", Technique: "T1195.001",
				Evidence: fmt.Sprintf("%s is edit-distance 1 from popular %s package %q; name shape only, not evidence of malice", lfLabel(c), c.Eco, pop), Weight: lfWTyposquat})
		}
	}
}

// lfEmitMalicious flags components whose name (or purl, or name@version)
// equals an enabled entry in the IOC store. Nothing is added to the store.
func lfEmitMalicious(b *InspectBuilder, comps []lfComp) {
	n := 0
	for _, c := range comps {
		cands := []string{c.Name, lfLabel(c), lfPurl(c)}
		matched := ""
		for _, cand := range cands {
			for _, m := range MatchIOCs(cand) {
				if strings.EqualFold(m.Value, cand) {
					matched = m.ID
					break
				}
			}
			if matched != "" {
				break
			}
		}
		if matched == "" {
			continue
		}
		if n++; n > 20 {
			b.LimitHit("known-malicious-findings")
			return
		}
		b.Finding(InspectFinding{ID: "sca-known-malicious", Title: "Dependency name matches an IOC-store entry", Severity: "high", Technique: "T1195.001",
			Evidence: fmt.Sprintf("%s [%s] matches IOC %s", lfLabel(c), c.Eco, matched), Weight: lfWKnownMal})
	}
}
