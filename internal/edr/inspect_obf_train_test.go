const (
	obfTrainSeed = 20240601
	obfEvalSeed  = 777001
	obfPerLang   = 150
)

type obfLabeled struct {
	s obfSample
	f ObfFeatures
}

func obfFeaturize(samples []obfSample) []obfLabeled {
	out := make([]obfLabeled, len(samples))
	for i, s := range samples {
		out[i] = obfLabeled{s, ObfExtract(s.Text, obfDetectLang("", s.Text))}
	}
	return out
}

func obfTrainLogistic(data []obfLabeled) obfModelT {
	nf, n := len(obfFeatureNames), len(data)
	m := obfModelT{Mean: make([]float64, nf), Std: make([]float64, nf), W: make([]float64, nf)}
	for j := 0; j < nf; j++ {
		var s float64
		for _, d := range data {
			s += d.f.V[j]
		}
		m.Mean[j] = s / float64(n)
		var v float64
		for _, d := range data {
			v += (d.f.V[j] - m.Mean[j]) * (d.f.V[j] - m.Mean[j])
		}
		m.Std[j] = math.Sqrt(v / float64(n))
		if m.Std[j] < 1e-9 {
			m.Std[j] = 1
		}
	}
	X := make([][]float64, n)
	y := make([]float64, n)
	for i, d := range data {
		X[i] = make([]float64, nf)
		for j := range X[i] {
			X[i][j] = (d.f.V[j] - m.Mean[j]) / m.Std[j]
		}
		if d.s.Obf {
			y[i] = 1
		}
	}
	const lr, l2, iters = 0.5, 1e-3, 3000
	grad := make([]float64, nf)
	for it := 0; it < iters; it++ {
		for j := range grad {
			grad[j] = 0
		}
		var gb float64
		for i := range X {
			z := m.Bias
			for j, x := range X[i] {
				z += m.W[j] * x
			}
			e := 1/(1+math.Exp(-z)) - y[i]
			gb += e
			for j, x := range X[i] {
				grad[j] += e * x
			}
		}
		m.Bias -= lr * gb / float64(n)
		for j := range m.W {
			m.W[j] -= lr * (grad[j]/float64(n) + l2*m.W[j])
		}
	}
	// threshold calibration on the training set
	bestF1, bestT := -1.0, 0.5
	for t := 30; t <= 95; t++ {
		th := float64(t) / 100
		var tp, fp, fn, tn float64
		for _, d := range data {
			pred := m.Prob(d.f) >= th
			switch {
			case pred && d.s.Obf:
				tp++
			case pred:
				fp++
			case d.s.Obf:
				fn++
			default:
				tn++
			}
		}
		if fp/(fp+tn) > 0.01 {
			continue
		}
		if f1 := 2 * tp / (2*tp + fp + fn); f1 > bestF1 {
			bestF1, bestT = f1, th
		}
	}
	m.Threshold = bestT
	return m
}

func obfWeightsSource(m obfModelT) string {
	var sb strings.Builder
	sb.WriteString("// SPDX-License-Identifier: LicenseRef-Zyvor-Production-1.0\npackage edr\n\n")
	sb.WriteString("// Code generated by TestObfTrain (KAVACH_OBF_WRITE=1); DO NOT EDIT.\n")
	sb.WriteString("// Logistic model over the standardized features in obfFeatureNames order,\n")
	sb.WriteString("// trained on the synthetic corpus described in inspect_obf_train_test.go.\n\n")
	arr := func(name string, xs []float64) {
		fmt.Fprintf(&sb, "\t%s: []float64{\n", name)
		for i, x := range xs {
			fmt.Fprintf(&sb, "\t\t%.6g, // %s\n", x, obfFeatureNames[i])
		}
		sb.WriteString("\t},\n")
	}
	sb.WriteString("var obfTrained = obfModelT{\n")
	arr("Mean", m.Mean)
	arr("Std", m.Std)
	arr("W", m.W)
	fmt.Fprintf(&sb, "\tBias:      %.6g,\n\tThreshold: %.2f,\n}\n", m.Bias, m.Threshold)
	return sb.String()
}

func TestObfTrain(t *testing.T) {
	if raceEnabled {
		t.Skip("sequential, goroutine-free reproducibility check (~90 s under -race); runs in the non-race job")
	}
	data := obfFeaturize(obfGenerate(obfTrainSeed, obfPerLang))
	m := obfTrainLogistic(data)
	if os.Getenv("KAVACH_OBF_WRITE") != "" {
		if err := os.WriteFile("inspect_obf_weights.go", []byte(obfWeightsSource(m)), 0o644); err != nil {
			t.Fatal(err)
		}
		t.Logf("wrote inspect_obf_weights.go threshold=%.2f", m.Threshold)
		return
	}
	// reproducibility: the committed weights must equal a fresh training run
	if len(obfTrained.W) != len(m.W) {
		t.Fatalf("committed model has %d weights, retrain has %d", len(obfTrained.W), len(m.W))
	}
	for i := range m.W {
		if math.Abs(obfTrained.W[i]-m.W[i]) > 1e-4*(1+math.Abs(m.W[i])) {
			t.Fatalf("weight %s differs: committed %g retrained %g (rerun with KAVACH_OBF_WRITE=1)", obfFeatureNames[i], obfTrained.W[i], m.W[i])
		}
	}
	if obfTrained.Threshold != m.Threshold {
		t.Fatalf("threshold differs: %v vs %v", obfTrained.Threshold, m.Threshold)
	}
}

