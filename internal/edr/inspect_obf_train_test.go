type obfCounts struct{ tp, fp, fn, tn int }

func (c obfCounts) prec() float64 {
	if c.tp+c.fp == 0 {
		return 1
	}
	return float64(c.tp) / float64(c.tp+c.fp)
}
func (c obfCounts) rec() float64 {
	if c.tp+c.fn == 0 {
		return 1
	}
	return float64(c.tp) / float64(c.tp+c.fn)
}
func (c obfCounts) f1() float64 {
	p, r := c.prec(), c.rec()
	if p+r == 0 {
		return 0
	}
	return 2 * p * r / (p + r)
}
func (c *obfCounts) add(pred, truth bool) {
	switch {
	case pred && truth:
		c.tp++
	case pred:
		c.fp++
	case truth:
		c.fn++
	default:
		c.tn++
	}
}

func TestObfEvaluation(t *testing.T) {
	if len(obfTrained.W) == 0 {
		t.Skip("model not trained")
	}
	samples := obfGenerate(obfEvalSeed, scaleN(obfPerLang, 60))
	data := obfFeaturize(samples)
	var all obfCounts
	byLang := map[string]*obfCounts{}
	techAll := map[string]*obfCounts{}    // recall among samples containing the technique
	techSingle := map[string]*obfCounts{} // samples with exactly that technique
	langDetectOK := 0
	var fpList []string
	nBenign, nObf := 0, 0
	for _, d := range data {
		pred := obfTrained.Prob(d.f) >= obfTrained.Threshold
		all.add(pred, d.s.Obf)
		if byLang[d.s.Lang] == nil {
			byLang[d.s.Lang] = &obfCounts{}
		}
		byLang[d.s.Lang].add(pred, d.s.Obf)
		if d.f.Lang == d.s.Lang {
			langDetectOK++
		}
		if d.s.Obf {
			nObf++
			for _, tc := range d.s.Techs {
				if techAll[tc] == nil {
					techAll[tc] = &obfCounts{}
				}
				techAll[tc].add(pred, true)
				if len(d.s.Techs) == 1 {
					if techSingle[tc] == nil {
						techSingle[tc] = &obfCounts{}
					}
					techSingle[tc].add(pred, true)
				}
			}
		} else {
			nBenign++
			if pred && len(fpList) < 12 {
				fpList = append(fpList, fmt.Sprintf("[%s] %s", d.s.Lang, strings.ReplaceAll(truncObf(d.s.Text, 110), "\n", " / ")))
			}
		}
	}
	// tricky benign
	var trickyFP []string
	tricky := obfTrickyBenign()
	for _, tr := range tricky {
		f := ObfExtract(tr.text, obfDetectLang("", tr.text))
		if p := obfTrained.Prob(f); p >= obfTrained.Threshold {
			trickyFP = append(trickyFP, fmt.Sprintf("%s (p=%.2f)", tr.name, p))
		}
	}

	var md strings.Builder
	fmt.Fprintf(&md, "Eval corpus seed %d: %d benign, %d obfuscated. Threshold %.2f.\n\n", obfEvalSeed, nBenign, nObf, obfTrained.Threshold)
	fmt.Fprintf(&md, "Overall: precision %.3f recall %.3f F1 %.3f (TP %d FP %d FN %d TN %d). Language auto-detection matched the generator label on %.1f%% of samples.\n\n", all.prec(), all.rec(), all.f1(), all.tp, all.fp, all.fn, all.tn, 100*float64(langDetectOK)/float64(len(data)))
	md.WriteString("| Language | Precision | Recall | F1 | TP | FP | FN | TN |\n|---|---|---|---|---|---|---|---|\n")
	for _, l := range obfLangs {
		c := byLang[l]
		fmt.Fprintf(&md, "| %s | %.3f | %.3f | %.3f | %d | %d | %d | %d |\n", l, c.prec(), c.rec(), c.f1(), c.tp, c.fp, c.fn, c.tn)
	}
	md.WriteString("\n| Technique | Recall (any sample containing it) | n | Recall (technique alone) | n alone |\n|---|---|---|---|---|\n")
	for _, tc := range obfAllTechs {
		a, s := techAll[tc], techSingle[tc]
		if a == nil {
			continue
		}
		sr, sn := "-", 0
		if s != nil {
			sr, sn = fmt.Sprintf("%.3f", s.rec()), s.tp+s.fn
		}
		fmt.Fprintf(&md, "| %s | %.3f | %d | %s | %d |\n", tc, a.rec(), a.tp+a.fn, sr, sn)
	}
	fmt.Fprintf(&md, "\nTricky benign: %d cases, %d false positives: %s\n\n", len(tricky), len(trickyFP), strings.Join(trickyFP, ", "))
	fmt.Fprintf(&md, "Synthetic benign false positives (first %d): \n", len(fpList))
	for _, s := range fpList {
		md.WriteString("- " + s + "\n")
	}
	if p := os.Getenv("KAVACH_OBF_REPORT"); p != "" {
		os.WriteFile(p, []byte(md.String()), 0o644)
	}
	t.Log("\n" + md.String())

	// failing floors (set below the measured values with margin)
	if all.f1() < 0.88 {
		t.Errorf("overall F1 %.3f below floor 0.88", all.f1())
	}
	if all.prec() < 0.95 || all.rec() < 0.78 {
		t.Errorf("precision %.3f / recall %.3f below floors", all.prec(), all.rec())
	}
	for _, l := range obfLangs {
		if byLang[l].f1() < 0.78 {
			t.Errorf("%s F1 %.3f below floor 0.78", l, byLang[l].f1())
		}
	}
	if float64(len(trickyFP)) > 0.2*float64(len(tricky)) {
		t.Errorf("too many tricky-benign false positives: %v", trickyFP)
	}
}

func truncObf(s string, n int) string {
	if len(s) <= n {
		return s
	}
	return s[:n] + "..."
}

