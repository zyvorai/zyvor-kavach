// Training, calibration and evaluation of the obfuscation-stats model.
//
// Procedure (fully deterministic, no external data):
//   1. corpus = obfGenerate(seed 20240601, 150 per language per class)  [train]
//   2. features = ObfExtract(text, obfDetectLang(text))  (end-to-end language detection)
//   3. standardize each feature (mean/std of the training set)
//   4. logistic regression, batch gradient descent, lr 0.5, L2 1e-3,
//      3000 iterations, zero initial weights
//   5. threshold = the p in {0.30..0.95 step 0.01} maximizing F1 on the train
//      set subject to train false-positive rate <= 1%
// Evaluation uses obfGenerate(seed 777001, ...) with the SAME generators, so it
// is not independent evidence of real-world accuracy.
//
// Regenerate the committed weights:
//   KAVACH_OBF_WRITE=1 go test ./internal/edr -run TestObfTrain
// Write the markdown evaluation tables:
//   KAVACH_OBF_REPORT=/path/report.md go test ./internal/edr -run TestObfEvaluation

