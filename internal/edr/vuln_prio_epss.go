// Opt-in FIRST EPSS feed (observation only). Default OFF: enabled only by
// KAVACH_EPSS_FEED=on. Same discipline as vuln_feeds.go:
//
//   - one allowlisted host, https only, redirects re-checked (max 3);
//   - the request is a plain GET of the public bulk file: no query string, no
//     body, no hostnames, IPs, package names or CVE ids from this install;
//   - the bulk file is filtered LOCALLY to the CVEs we care about, so FIRST
//     never learns which CVEs matched anything here;
//   - 30s timeout (60s per refresh context cap in the handler), compressed
//     body limit 16 MiB, decompressed limit 64 MiB;
//   - cached at <store>.epss.json; requests never block on the network.
//
// Data: EPSS scores published by the FIRST EPSS SIG, generated by Empirical
// Security, "published freely to the community" (first.org/epss/data). No
// licence text was found; attribution is requested by FIRST. See
// docs/research-vuln-priority.md.

var (
	vpEPSSURL      = "https://epss.empiricalsecurity.com/epss_scores-current.csv.gz"
	vpEPSSHosts    = map[string]bool{"epss.empiricalsecurity.com": true}
	vpEPSSInsecure = false // tests only: allow http to httptest servers
)

const (
	vpEPSSMaxGz      = 16 << 20
	vpEPSSMaxRaw     = 64 << 20
	vpEPSSMaxEntries = 50000
	vpEPSSInterval   = 24 * time.Hour
	vpEPSSAttrib     = "EPSS is maintained by the EPSS Special Interest Group at FIRST. Scores are generated by Empirical Security and published freely to the community."

	// EPSSPoCThreshold: EPSS at or above this maps Exploitation to "poc".
	// 0.10 is a Kavach policy choice (NOT from the SSVC guide or FIRST): it
	// means "at least a 10% modelled chance of exploitation activity in the
	// next 30 days". Below it, exploitation stays unknown.
	vpEPSSPoCThreshold = 0.10
)

type vpEPSSScore struct {
	EPSS       float64 `json:"epss"`
	Percentile float64 `json:"percentile"`
}

type vpEPSSCache struct {
	Scores       map[string]vpEPSSScore `json:"scores"`
	ModelVersion string                 `json:"model_version"`
	ScoreDate    string                 `json:"score_date"`
	Fetched      time.Time              `json:"fetched"`
	Rows         int                    `json:"source_rows"`
}

type vpEPSSFeed struct {
	mu      sync.Mutex
	cache   vpEPSSCache
	path    string
	last    time.Time
	errs    []string
	started bool
	client  *http.Client
	// wanted returns the CVEs to retain (inventory-derived, local only).
	wanted func() map[string]bool
}

var vpEPSS = &vpEPSSFeed{cache: vpEPSSCache{Scores: map[string]vpEPSSScore{}}}

func vpEPSSEnabled() bool {
	return strings.EqualFold(strings.TrimSpace(os.Getenv("KAVACH_EPSS_FEED")), "on")
}

// SetEPSSCachePath sets and loads the on-disk cache (<store>.epss.json).
func SetEPSSCachePath(p string) {
	f := vpEPSS
	f.mu.Lock()
	defer f.mu.Unlock()
	f.path = p
	b, err := os.ReadFile(p)
	if err != nil {
		return
	}
	var c vpEPSSCache
	if err := json.Unmarshal(b, &c); err != nil {
		f.errs = append(f.errs, "cache parse: "+err.Error())
		log.Printf("kavach epss: cache parse error: %v", err)
		return
	}
	if c.Scores == nil {
		c.Scores = map[string]vpEPSSScore{}
	}
	f.cache = c
}

func vpCheckURL(u *url.URL) error {
	if vpEPSSInsecure {
		return nil
	}
	if u.Scheme != "https" || !vpEPSSHosts[strings.ToLower(u.Hostname())] {
		return fmt.Errorf("blocked outbound url (host %q not allowlisted or not https)", u.Hostname())
	}
	return nil
}

func (f *vpEPSSFeed) httpClient() *http.Client {
	if f.client != nil {
		return f.client
	}
	return &http.Client{Timeout: 30 * time.Second, CheckRedirect: func(req *http.Request, via []*http.Request) error {
		if len(via) >= 3 {
			return errors.New("too many redirects")
		}
		return vpCheckURL(req.URL)
	}}
}

// Lookup returns the cached score for a CVE.
func (f *vpEPSSFeed) Lookup(cve string) (vpEPSSScore, bool) {
	f.mu.Lock()
	defer f.mu.Unlock()
	s, ok := f.cache.Scores[strings.ToUpper(cve)]
	return s, ok
}

// Refresh downloads the bulk file and keeps only wanted CVEs.
func (f *vpEPSSFeed) Refresh(ctx context.Context) map[string]any {
	err := f.refresh(ctx)
	f.mu.Lock()
	if err != nil {
		f.errs = []string{err.Error()}
		log.Printf("kavach epss: %v", err)
	} else {
		f.errs = nil
		f.last = time.Now().UTC()
	}
	f.mu.Unlock()
	f.save()
	return f.Status()
}

func (f *vpEPSSFeed) refresh(ctx context.Context) error {
	u, err := url.Parse(vpEPSSURL)
	if err != nil {
		return err
	}
	if err := vpCheckURL(u); err != nil {
		return err
	}
	// Plain GET: nothing but a static User-Agent is sent.
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, vpEPSSURL, nil)
	if err != nil {
		return err
	}
	req.Header.Set("User-Agent", "kavach-epss-feed")
	resp, err := f.httpClient().Do(req)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	if resp.StatusCode != 200 {
		return fmt.Errorf("%s: http %d", u.Hostname(), resp.StatusCode)
	}
	gzr, err := gzip.NewReader(io.LimitReader(resp.Body, vpEPSSMaxGz+1))
	if err != nil {
		return fmt.Errorf("gzip: %w", err)
	}
	raw := &limitedReader{r: gzr, n: vpEPSSMaxRaw}
	var want map[string]bool
	if f.wanted != nil {
		want = f.wanted()
	}
	sc := bufio.NewScanner(raw)
	sc.Buffer(make([]byte, 0, 64*1024), 1<<20)
	c := vpEPSSCache{Scores: map[string]vpEPSSScore{}}
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		switch {
		case line == "":
		case strings.HasPrefix(line, "#"):
			for _, kv := range strings.Split(strings.TrimPrefix(line, "#"), ",") {
				k, v, _ := strings.Cut(kv, ":")
				switch strings.TrimSpace(k) {
				case "model_version":
					c.ModelVersion = strings.TrimSpace(v)
				case "score_date":
					c.ScoreDate = strings.TrimSpace(v)
				}
			}
		case strings.HasPrefix(line, "cve,"):
		default:
			p := strings.Split(line, ",")
			if len(p) < 3 {
				continue
			}
			c.Rows++
			id := strings.ToUpper(strings.TrimSpace(p[0]))
			if !want[id] || len(c.Scores) >= vpEPSSMaxEntries {
				continue
			}
			e, err1 := strconv.ParseFloat(p[1], 64)
			pc, err2 := strconv.ParseFloat(p[2], 64)
			if err1 != nil || err2 != nil || e < 0 || e > 1 || pc < 0 || pc > 1 {
				continue
			}
			c.Scores[id] = vpEPSSScore{EPSS: e, Percentile: pc}
		}
	}
	if err := sc.Err(); err != nil {
		return fmt.Errorf("read: %w", err)
	}
	if raw.exceeded {
		return fmt.Errorf("decompressed body exceeds %d bytes", vpEPSSMaxRaw)
	}
	if c.Rows == 0 {
		return errors.New("parse: no score rows")
	}
	c.Fetched = time.Now().UTC()
	f.mu.Lock()
	f.cache = c
	f.mu.Unlock()
	return nil
}

// limitedReader errors (and flags) when more than n bytes are read.
type limitedReader struct {
	r        io.Reader
	n        int64
	exceeded bool
}

func (l *limitedReader) Read(p []byte) (int, error) {
	if l.n <= 0 {
		l.exceeded = true
		return 0, io.EOF
	}
	if int64(len(p)) > l.n {
		p = p[:l.n]
	}
	n, err := l.r.Read(p)
	l.n -= int64(n)
	return n, err
}

func (f *vpEPSSFeed) save() {
	f.mu.Lock()
	defer f.mu.Unlock()
	if f.path == "" {
		return
	}
	b, err := json.Marshal(f.cache)
	if err == nil {
		tmp := f.path + ".tmp"
		if err = os.WriteFile(tmp, b, 0o600); err == nil {
			err = os.Rename(tmp, f.path)
		}
	}
	if err != nil {
		f.errs = append(f.errs, "cache write: "+err.Error())
		log.Printf("kavach epss: cache write: %v", err)
	}
}

// Status reports feed state.
func (f *vpEPSSFeed) Status() map[string]any {
	on := vpEPSSEnabled()
	f.mu.Lock()
	defer f.mu.Unlock()
	st := map[string]any{
		"enabled": on, "source": "none", "cached_cves": len(f.cache.Scores),
		"model_version": f.cache.ModelVersion, "score_date": f.cache.ScoreDate,
		"last_refresh": f.last, "cache_fetched": f.cache.Fetched,
		"feed_errors": append([]string{}, f.errs...), "attribution": vpEPSSAttrib,
	}
	if on {
		st["source"] = "feed:epss"
		st["note"] = "plain GET of the public daily EPSS file; filtered locally; no host, inventory or CVE data is sent"
	} else {
		st["note"] = "EPSS feed disabled (set KAVACH_EPSS_FEED=on to opt in); no network traffic; EPSS stays unknown"
	}
	return st
}

// Start launches the 24h background refresh when the feed is enabled.
func (f *vpEPSSFeed) Start() {
	if !vpEPSSEnabled() {
		return
	}
	f.mu.Lock()
	if f.started {
		f.mu.Unlock()
		return
	}
	f.started = true
	f.mu.Unlock()
	go func() {
		for {
			ctx, cancel := context.WithTimeout(context.Background(), 2*time.Minute)
			f.Refresh(ctx)
			cancel()
			time.Sleep(vpEPSSInterval)
		}
	}()
}
