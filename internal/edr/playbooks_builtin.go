package edr

// Built-in advisory response playbook templates. Every action is either an
// analyst task ("analyst: ...") or a ledger request ("ledger: ..."). Kavach is
// observation-only: nothing here is executed against any host.

func bp(id, name, trigger, desc string, steps ...string) Playbook {
	steps = append(steps, "ledger: record outcome and evidence references in the case notes")
	return Playbook{ID: "bp-" + id, Name: name, Trigger: trigger, Actions: steps, Enabled: true,
		Description: "Advisory runbook (analyst actions and ledger requests only). " + desc}
}

