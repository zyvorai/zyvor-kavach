// Copies top-level ../docs/*.md into website/docs/ so the site stays aligned
// with the repo docs. Run by prebuild/prestart.
import {readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync} from 'node:fs';
import {dirname, join, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const site = resolve(here, '..');
const rootDocs = resolve(site, '../docs');
const outDir = join(site, 'docs');

mkdirSync(outDir, {recursive: true});

const files = readdirSync(rootDocs).filter((f) => f.endsWith('.md'));
for (const name of files) {
  const src = join(rootDocs, name);
  const dest = join(outDir, name);
  const raw = readFileSync(src, 'utf8');
  const lines = raw.split('\n');
  const h1 = lines.findIndex((l) => l.startsWith('# '));
  const title = h1 >= 0 ? lines[h1].slice(2).trim() : name.replace(/\.md$/, '');
  const body =
    h1 >= 0
      ? [...lines.slice(0, h1), ...lines.slice(h1 + 1)].join('\n').replace(/^\s*\n/, '')
      : raw;
  const out = [
    '---',
    `title: ${JSON.stringify(title)}`,
    '---',
    '',
    `<!-- GENERATED by website/scripts/sync-docs.mjs from docs/${name}. Edit the source. -->`,
    '',
    body.endsWith('\n') ? body : body + '\n',
  ].join('\n');
  writeFileSync(dest, out.endsWith('\n') ? out : out + '\n');
}

if (!existsSync(join(outDir, 'intro.md'))) {
  writeFileSync(
    join(outDir, 'intro.md'),
    [
      '---',
      'title: "Intro"',
      'sidebar_position: 1',
      '---',
      '',
      '# Kavach',
      '',
      'See the repository README for quickstart.',
      '',
    ].join('\n'),
  );
}

console.log(`synced ${files.length} docs → website/docs/`);
