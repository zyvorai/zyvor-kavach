#!/usr/bin/env ruby
# Regenerates the "Feature inventory" block in docs/index.md from repository
# facts, so the numbers are never hand-typed.
#
#   ruby docs/tools/inventory.rb           # print the block
#   ruby docs/tools/inventory.rb --write   # replace the block in docs/index.md
#   ruby docs/tools/inventory.rb --check   # exit 1 if docs/index.md is stale
#
# Run from anywhere; paths are resolved relative to this file. Only the Ruby
# standard library is used. Counts:
#   operations / paths  docs/openapi.yaml (internal/edr/openapi_routes_test.go
#                       fails if a registered route is missing from it)
#   rules, packs        internal/edr/content/*.json (detection), bytecontent/*.json
#   policies            internal/edr/configpolicies/*.json
#   profiles            internal/edr/adversaries/*.json
#   scenarios           internal/edr/scenarios/*.json (+ declared not_testable)
require "json"

ROOT = File.expand_path("../..", __dir__)
EDR = File.join(ROOT, "internal", "edr")
INDEX = File.join(ROOT, "docs", "index.md")
BEGIN_MARK = "<!-- inventory:begin (generated by docs/tools/inventory.rb; do not edit) -->"
END_MARK = "<!-- inventory:end -->"

def jload(f) = JSON.parse(File.read(f))

def count_list(glob, key)
  files = Dir[File.join(EDR, glob)].sort
  n = files.sum { |f| j = jload(f); (j.is_a?(Hash) ? j[key] : j).size }
  [files.size, n]
end

ops = 0
paths = 0
in_paths = false
cur = nil
File.readlines(File.join(ROOT, "docs", "openapi.yaml")).each do |l|
  if l.start_with?("paths:") then in_paths = true; next end
  break if in_paths && l =~ /\A\S/
  next unless in_paths
  if l =~ /\A  (\/\S*):\s*\z/ then paths += 1; cur = $1; next end
  ops += 1 if l =~ /\A    (get|post|put|delete|patch):\s*\z/
end

det_packs, det_rules = count_list("content/*.json", "rules")
byte_packs, byte_rules = count_list("bytecontent/*.json", "rules")
_, policies = count_list("configpolicies/*.json", "policies")
adv_files, adv_profiles = count_list("adversaries/*.json", "profiles")
scen = Dir[File.join(EDR, "scenarios", "*.json")].sort.sum do |f|
  j = jload(f)
  next 0 if j.key?("not_testable")
  j["scenarios"].size
end
not_testable = jload(File.join(EDR, "scenarios", "not_testable.json"))["not_testable"].size
matrix = jload(File.join(EDR, "competitive_matrix.json"))
backlog = matrix["backlog"]
shipped = backlog.count { |b| b["status"] == "implemented" }
partial = backlog.count { |b| b["status"] == "partial" }
docs = Dir[File.join(ROOT, "docs", "*.md")].size
cmds = Dir[File.join(ROOT, "cmd", "*")].select { |d| File.directory?(d) }.map { |d| File.basename(d) }.sort

block = <<~MD
  #{BEGIN_MARK}
  | Fact | Count |
  |------|------:|
  | HTTP operations documented in `docs/openapi.yaml` | #{ops} |
  | Distinct API paths | #{paths} |
  | Detection rule packs (`internal/edr/content/*.json`) | #{det_packs} |
  | Detection rules | #{det_rules} |
  | Byte-pattern (inspector) packs / rules | #{byte_packs} / #{byte_rules} |
  | Configuration assessment policies | #{policies} |
  | Adversary profile files / profiles | #{adv_files} / #{adv_profiles} |
  | Validation scenarios (plus #{not_testable} declared not testable) | #{scen} |
  | Competitive backlog items implemented / partial / total | #{shipped} / #{partial} / #{backlog.size} |
  | Markdown docs in `docs/` | #{docs} |
  | Binaries in `cmd/` | #{cmds.size} (#{cmds.join(', ')}) |

  Refresh with `ruby docs/tools/inventory.rb --write`. Counts are read from the files, not typed by hand.
  #{END_MARK}
MD

case ARGV[0]
when "--write"
  t = File.read(INDEX)
  re = /#{Regexp.escape(BEGIN_MARK)}.*?#{Regexp.escape(END_MARK)}\n/m
  abort "markers not found in docs/index.md" unless t =~ re
  File.write(INDEX, t.sub(re) { block })
  puts "updated #{INDEX}"
when "--check"
  t = File.read(INDEX)
  abort "docs/index.md inventory is stale; run ruby docs/tools/inventory.rb --write" unless t.include?(block)
  puts "inventory up to date"
else
  puts block
end
